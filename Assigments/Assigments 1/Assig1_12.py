# Find the volume of sphere.

# Formula :

# v = Volume of sphere
# R = Redius of sphere

# volume = (4/3) *  π * r**3

import math 

radius = float(input("Enter thr radius of sphere :")) #input the radius 

volume = (4/3)* math.pi * radius ** 3 #calculate volume of sphere

print("Volume of sphere =",volume) # output volume of sphere