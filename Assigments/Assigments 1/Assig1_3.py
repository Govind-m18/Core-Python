# Program to find quotient and remainder of two numbers.

#formula :

# quotient = dividend // divisor
# remainder = divident % divisor

Divident = int(input("Enter Divident :")) #taking divident for calculating quotioent and remainder of tow numbers.
Divisor = int(input("Enter Divisor :"))

Quotient = Divident // Divisor # calculating quotient of two numbers.
Remainder = Divident % Divisor # calculating remainder of two numbers.

print("Quotient of two numbers:",Quotient)
print("Remainder of two numbers:",Remainder)
