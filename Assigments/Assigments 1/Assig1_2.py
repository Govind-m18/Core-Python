# Write a program to calculate area of rectangle based on length and breadth.

#formula for calculate area of rectangle 

# area = length * breadth

length = float(input("Enter Length of rectangle :")) #we can use  float() for give decimal value of length.  ex : 4.78
breadth = float(input("Enter Breadth of rectangle :"))

area = length * breadth # calculating area of rectangle based on length and breadth.

print("Area of rectangle:",area)